// Draw the font into a CHR buffer: each glyph occupies tile ASCII(ch) at
// `base` (plane 0 only, color 1).
export function drawFontInto(chr, base = 0) {
  for (const [ch, rows] of Object.entries(GLYPHS)) {
    const tile = (base + ch.charCodeAt(0)) * 16;
    rows.forEach((v, r) => { chr[tile + r] = v; });
  }
}
